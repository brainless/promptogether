//! Deterministic TypeScript binding exporter for `api-types`.
//!
//! This binary calls `ts-rs` programmatically (via `TS::export` /
//! `TS::export_all`) to write one `.ts` binding per public wire type plus a
//! barrel (`index.ts`) into `webapp/src/api/generated/`.
//!
//! It intentionally does not rely on test-driven auto-export: generation is a
//! deliberate, reproducible command. Every exported file is byte-identical
//! across runs because `ts-rs` emits no timestamps or absolute paths and the
//! barrel uses a fixed, sorted declaration order.

use api_types::error::ErrorResponse;
use api_types::gallery::{
    GalleryProjectDetail, GalleryProjectFile, GalleryProjectFilePhase, GalleryProjectSummary,
};
use api_types::health::{HealthResponse, HealthStatus};
use std::env;
use std::fs::{self, File};
use std::io::{self, Read};
use std::path::{Path, PathBuf};
use ts_rs::Config;
use ts_rs::TS;

const NOTE: &str = "// This file was generated by [ts-rs](https://github.com/Aleph-Alpha/ts-rs). Do not edit this file manually.\n";

/// The set of public wire types to export, in a fixed, documented order.
///
/// The five `#[ts(export)]` structs are required; the two helper enums
/// (`HealthStatus`, `GalleryProjectFilePhase`) are exported explicitly so the
/// webapp can reference them directly. The order is fixed (alphabetical) so
/// the barrel file is deterministic.
///
/// `ExportKind::All` uses `TS::export_all`, which also writes every dependency
/// of the type to its derived path. This is required for `ErrorResponse`,
/// whose `serde_json::Value` field imports a generated `serde_json/JsonValue`
/// binding that must exist on disk. `ExportKind::Single` writes only that type.
enum ExportKind {
    All,
    Single,
}

fn export_types(cfg: &Config) -> Vec<(&'static str, ExportKind, Result<(), String>)> {
    fn export_all<T: TS + 'static>(cfg: &Config) -> Result<(), String> {
        T::export_all(cfg).map_err(|e| format!("{e}"))
    }
    fn export<T: TS + 'static>(cfg: &Config) -> Result<(), String> {
        T::export(cfg).map_err(|e| format!("{e}"))
    }

    let mut types: Vec<(&str, ExportKind, Result<(), String>)> = vec![
        ("HealthResponse", ExportKind::All, export_all::<HealthResponse>(cfg)),
        ("HealthStatus", ExportKind::Single, export::<HealthStatus>(cfg)),
        ("ErrorResponse", ExportKind::All, export_all::<ErrorResponse>(cfg)),
        (
            "GalleryProjectSummary",
            ExportKind::All,
            export_all::<GalleryProjectSummary>(cfg),
        ),
        (
            "GalleryProjectFilePhase",
            ExportKind::Single,
            export::<GalleryProjectFilePhase>(cfg),
        ),
        (
            "GalleryProjectFile",
            ExportKind::All,
            export_all::<GalleryProjectFile>(cfg),
        ),
        (
            "GalleryProjectDetail",
            ExportKind::All,
            export_all::<GalleryProjectDetail>(cfg),
        ),
    ];

    // Keep the barrel ordering deterministic regardless of the order above.
    types.sort_by(|a, b| a.0.cmp(b.0));
    types
}

fn default_export_dir() -> PathBuf {
    PathBuf::from("webapp")
        .join("src")
        .join("api")
        .join("generated")
}

/// Remove bindings created by an earlier exporter run.
///
/// The output directory can be overridden, so it is not safe to replace the
/// directory wholesale. Only regular files carrying the exporter's generated
/// header are removed, and symlinks are never followed. A nested directory is
/// removed only when generated files were removed from it and it became empty.
fn remove_stale_bindings(dir: &Path) -> Result<bool, String> {
    let mut entries = fs::read_dir(dir)
        .map_err(|e| format!("failed to read {}: {e}", dir.display()))?
        .collect::<Result<Vec<_>, _>>()
        .map_err(|e| format!("failed to read an entry in {}: {e}", dir.display()))?;
    entries.sort_by_key(|entry| entry.file_name());

    let mut removed_any = false;

    for entry in entries {
        let path = entry.path();
        let file_type = entry
            .file_type()
            .map_err(|e| format!("failed to inspect {}: {e}", path.display()))?;

        if file_type.is_dir() {
            let removed_from_child = remove_stale_bindings(&path)?;
            if removed_from_child
                && fs::read_dir(&path)
                    .map_err(|e| format!("failed to read {}: {e}", path.display()))?
                    .next()
                    .is_none()
            {
                fs::remove_dir(&path)
                    .map_err(|e| format!("failed to remove {}: {e}", path.display()))?;
            }
            removed_any |= removed_from_child;
        } else if file_type.is_file() && has_generated_header(&path)? {
            fs::remove_file(&path)
                .map_err(|e| format!("failed to remove {}: {e}", path.display()))?;
            removed_any = true;
        }
    }

    Ok(removed_any)
}

fn has_generated_header(path: &Path) -> Result<bool, String> {
    let mut header = vec![0; NOTE.len()];
    let mut file = File::open(path)
        .map_err(|e| format!("failed to open {}: {e}", path.display()))?;

    match file.read_exact(&mut header) {
        Ok(()) => Ok(header == NOTE.as_bytes()),
        Err(e) if e.kind() == io::ErrorKind::UnexpectedEof => Ok(false),
        Err(e) => Err(format!("failed to read {}: {e}", path.display())),
    }
}

fn main() {
    // `TS_RS_EXPORT_DIR` overrides the target directory (ts-rs convention).
    // Otherwise default to the workspace-relative generated directory.
    let out_dir = match env::var_os("TS_RS_EXPORT_DIR") {
        Some(dir) => PathBuf::from(dir),
        None => default_export_dir(),
    };
    let cfg = Config::new().with_out_dir(out_dir.clone());
    fs::create_dir_all(&out_dir).expect("failed to create output directory");
    remove_stale_bindings(&out_dir).expect("failed to remove stale generated bindings");

    let results = export_types(&cfg);

    let failures: Vec<String> = results
        .iter()
        .filter_map(|(name, _, res)| res.as_ref().err().map(|e| format!("{name}: {e}")))
        .collect();
    write_barrel(&out_dir, &results).expect("failed to write barrel file");

    if !failures.is_empty() {
        eprintln!("export failed:");
        for f in &failures {
            eprintln!("  {f}");
        }
        std::process::exit(1);
    }

    println!(
        "exported {} bindings + index.ts to {}",
        results.len(),
        out_dir.display()
    );
}

/// Write the barrel file re-exporting every generated binding.
///
/// `ts-rs` writes one file per type, so the barrel simply re-exports each by
/// its TypeScript type name. Names are emitted in the same sorted order as the
/// export results, keeping the output stable.
fn write_barrel(
    out_dir: &PathBuf,
    results: &[(&'static str, ExportKind, Result<(), String>)],
) -> Result<(), String> {
    let mut barrel = String::new();
    barrel.push_str(NOTE);
    barrel.push_str("\n// This barrel file re-exports every generated binding.\n");
    barrel.push_str("// Do not edit by hand; regenerate with the api-types exporter.\n\n");

    for (name, _, _) in results {
        barrel.push_str(&format!("export type {{ {name} }} from \"./{name}\";\n"));
    }

    fs::write(out_dir.join("index.ts"), barrel).map_err(|e| e.to_string())
}
